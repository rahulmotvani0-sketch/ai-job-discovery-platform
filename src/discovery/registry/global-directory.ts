/**
 * Returns portals filtered by category group.
 */
export function getGlobalPortalsByCategory(category: GlobalPortalCategoryGroup): GlobalPortalRegistryEntry[] {
  return GLOBAL_PORTALS_REGISTRY.filter(p => p.category === category);
}

/**
 * Returns portals supporting a specific country code (e.g., 'IN', 'US', 'GB') or 'GLOBAL'.
 */
export function getGlobalPortalsByCountry(country: string): GlobalPortalRegistryEntry[] {
  const upper = country.toUpperCase();
  return GLOBAL_PORTALS_REGISTRY.filter(p => p.countries.includes(upper) || p.countries.includes('GLOBAL'));
}

/**
 * Returns an aggregated summary of the Global Portals Registry across all 13 source-type groups.
 */
export function getGlobalPortalsSummary(): {
  total: number;
  byGroup: Record<GlobalPortalCategoryGroup, number>;
  implementedCount: number;
  partnerOrApiCount: number;
} {
  const byGroup: Record<GlobalPortalCategoryGroup, number> = {
    GLOBAL_GENERAL: 0,
    TECH_STARTUP: 0,
    REMOTE_WORK: 0,
    FREELANCE_CONTRACT: 0,
    INDIA: 0,
    US_CANADA: 0,
    UK_IRELAND: 0,
    EUROPE: 0,
    ASIA_PACIFIC: 0,
    MIDDLE_EAST_AFRICA: 0,
    LATIN_AMERICA: 0,
    PUBLIC_NONPROFIT: 0,
    DIRECT_ATS: 0,
  };

  let implementedCount = 0;
  let partnerOrApiCount = 0;

  for (const portal of GLOBAL_PORTALS_REGISTRY) {
    byGroup[portal.category] = (byGroup[portal.category] || 0) + 1;
    if (portal.connectorStatus === 'IMPLEMENTED_AND_TESTED') {
      implementedCount++;
    }
    if (portal.connectorStatus === 'REQUIRES_API_CREDENTIALS' || portal.connectorStatus === 'REQUIRES_PARTNER_ACCESS') {
      partnerOrApiCount++;
    }
  }

  return {
    total: GLOBAL_PORTALS_REGISTRY.length,
    byGroup,
    implementedCount,
    partnerOrApiCount,
  };
}

/**
 * Finds a portal by exact or substring name match.
 */
export function findPortalByName(name: string): GlobalPortalRegistryEntry | undefined {
  const lower = name.toLowerCase();
  return GLOBAL_PORTALS_REGISTRY.find(p => p.portalName.toLowerCase().includes(lower));
}
